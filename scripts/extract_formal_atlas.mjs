// Regenerates app/src/data/formalAtlas.ts from the Formal Atlas of Semantics data.
// Usage: node scripts/extract_formal_atlas.mjs ~/Dropbox/revisiting-formal-semantics/atlas_data/atlas.json
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const src = process.argv[2] || path.join(process.env.HOME, 'Dropbox/revisiting-formal-semantics/atlas_data/atlas.json');
const a = JSON.parse(readFileSync(src, 'utf8'));
const LABELS = {
  atlas__ptq: 'Montague PTQ', atlas__lambek: 'Lambek calculus', atlas__discocat: 'DisCoCat',
  atlas__mtt: 'Modern Type Theory', atlas__dts: 'Dependent Type Semantics', atlas__ranta: 'Ranta (constructive TT)',
  extras__BarwiseCooper: 'Barwise & Cooper GQ', shallow__kratzer2: 'Kratzer modality', atlas__ttr: 'Type Theory with Records',
};
const nodeFiles = {};
for (const e of a.edges) { nodeFiles[e.a] = e.a_file; nodeFiles[e.b] = e.b_file; }
const nodes = Object.entries(nodeFiles).map(([id, file]) => {
  const rec = a.files.find(f => f.file === file);
  return { id, label: LABELS[id] ?? id, file, region: rec?.region ?? null,
    theorems: rec?.counts?.theorems ?? null, proved: rec?.counts?.proved ?? null };
});
const edges = a.edges.map(e => ({ a: e.a, b: e.b, level: e.level, bridge: e.bridge_file,
  phenomena: e.phenomena.map(p => ({ name: p.name, grade: p.grade ?? null })) }));
const count = (arr, k) => arr.reduce((m, x) => (m[x[k]] = (m[x[k]] || 0) + 1, m), {});
const out = {
  source: 'revisiting-formal-semantics/atlas_data/atlas.json',
  generatedFrom: a.generated_from,
  stats: { theorems: a.stats.theorems, proved: a.stats.proved, admitted: a.stats.admitted, records: a.files.length },
  evidenceLevels: count(a.papers, 'level'),
  categories: count(a.papers.map(p => ({ c: `${p.category}` })), 'c'),
  topics: Object.keys(count(a.papers, 'topic')).length,
  paperYears: [Math.min(...a.papers.map(p => p.year).filter(Boolean)), Math.max(...a.papers.map(p => p.year).filter(Boolean))],
  grading: a.edges[0].grading,
  // one [P formality 0-5, F evidence level 0-5, year] triple per surveyed source
  papers: a.papers.map(p => [p.formality ?? null, p.level ? +p.level.slice(1) : null, p.year ?? null]),
  nodes, edges,
};
const here = path.dirname(fileURLToPath(import.meta.url));
const dest = path.join(here, '../app/src/data/formalAtlas.ts');
writeFileSync(dest, `// GENERATED by scripts/extract_formal_atlas.mjs from ${out.source}. Do not edit by hand.\n` +
  `export const formalAtlas = ${JSON.stringify(out, null, 2)};\n`);
console.log('wrote', dest, nodes.length, 'nodes', edges.length, 'edges', JSON.stringify(out.stats), JSON.stringify(out.evidenceLevels), JSON.stringify(out.categories), out.topics, out.paperYears);
console.log(nodes.map(n => `${n.id}:${n.region}:${n.theorems}`).join(' | '));
